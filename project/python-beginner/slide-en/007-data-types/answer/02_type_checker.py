# โจทย์: สร้าง variable 4 ตัวต่างชนิด แล้วแสดง type

# ตัวแปรแต่ละชนิด
my_age = 12          # int: จำนวนเต็ม
my_height = 1.55     # float: ทศนิยม
my_name = "Alice"    # str: ข้อความ
is_student = True    # bool: จริง/เท็จ

# แสดง type ของแต่ละตัวแปร
print(type(my_age))
print(type(my_height))
print(type(my_name))
print(type(is_student))
