# โจทย์: รับตัวเลข N แล้วแสดงตารางสูตรคูณของ N ตั้งแต่ 1 ถึง 10
# ผสมความรู้: for loop + range + input + การคำนวณในลูป

n = int(input())  # รับตัวเลขที่ต้องการหาตารางสูตรคูณ

# วนรอบ i ตั้งแต่ 1 ถึง 10
for i in range(1, 11):
    result = n * i  # คำนวณผลคูณในแต่ละรอบ
    # แสดงผลในรูปแบบ "N x i = result"
    print(f"{n} x {i} = {result}")
