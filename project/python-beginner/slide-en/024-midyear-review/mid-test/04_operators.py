# ข้อ 4 : Operators
# โจทย์: แสดงผลการคำนวณด้วย operator ทั้ง 6 แบบ

a = 17
b = 5

print(a, "+", b, "=", a + b)   # print(f"{a} + {b} = {a + b}")
print(a, "-", b, "=", a - b)   # print(f"{a} - {b} = {a - b}")
print(a, "*", b, "=", a * b)   # print(f"{a} * {b} = {a * b}")
print(a, "/", b, "=", a / b)   # print(f"{a} / {b} = {a / b}")
print(a, "//", b, "=", a // b) # print(f"{a} // {b} = {a // b}")
print(a, "%", b, "=", a % b)   # print(f"{a} % {b} = {a % b}")
