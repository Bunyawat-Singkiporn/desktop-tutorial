# โจทย์: เขียนโค้ดใหม่ด้วยชื่อ variable ที่สื่อความหมาย
# โค้ดเดิมใช้: a, b, c, d (ไม่บอกว่าเก็บอะไร)

# ✅ ชื่อ variable ที่ถูกต้องและสื่อความหมาย
product_name = "Laptop"
unit_price = 25000
quantity = 3
total_price = unit_price * quantity

# แสดงผล (Output เหมือนเดิม)
print(product_name)
print(unit_price)
print(quantity)
print(total_price)
