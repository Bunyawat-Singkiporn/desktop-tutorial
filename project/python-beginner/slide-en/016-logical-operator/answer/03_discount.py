# โจทย์: รับเงินและสถานะสมาชิก แล้วตรวจสอบว่าได้ส่วนลดหรือไม่
# - ต้องผ่านทั้งสองเงื่อนไข: เงิน >= 100 AND เป็นสมาชิก
# - ผ่านทั้งคู่ → แสดง Discount
# - ไม่ผ่าน → ไม่แสดงอะไร

money = int(input())  # รับจำนวนเงิน
member = input()      # รับค่า "True" หรือ "False" (เป็น string)

# หมายเหตุ: input() คืนค่าเป็น string เสมอ
# จึงต้องเปรียบเทียบกับ "True" (มีเครื่องหมายคำพูด)
if money >= 100 and member == "True":
    print("Discount")
