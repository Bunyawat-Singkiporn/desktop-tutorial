# โจทย์: คำนวณพื้นที่และเส้นรอบวงสี่เหลี่ยมผืนผ้า

# ขนาดของสี่เหลี่ยม
width = 5
height = 8

# คำนวณ
area = width * height            # พื้นที่ = กว้าง × สูง
perimeter = (width + height) * 2  # เส้นรอบวง = (กว้าง + สูง) × 2

# แสดงผล
print("Width:", width)
print("Height:", height)
print("Area:", area)
print("Perimeter:", perimeter)
