# โจทย์: รายงานนักเรียนด้วยชื่อ variable ที่ถูกต้องทั้งหมด

# ข้อมูลนักเรียน
student_name = "Mia"
class_grade = 6

# คะแนนแต่ละวิชา
math_score = 88
english_score = 92

# คำนวณค่าเฉลี่ย
average_score = (math_score + english_score) / 2

# แสดงรายงาน
print("=== Student Report ===")
print("Name  :", student_name)
print("Grade :", class_grade)
print("Math  :", math_score)
print("Eng   :", english_score)
print("Avg   :", average_score)
