# โจทย์: รับจำนวนเงิน แล้วแสดงสถานะ
# - 100 ขึ้นไป → Rich
# - 50 ถึง 99  → Normal
# - น้อยกว่า 50 → Poor

money = int(input())  # รับจำนวนเงินเป็น int

# เรียงเงื่อนไขจากมากไปน้อย
# ถ้าเงินถึง 100 จะไม่ผ่านมาถึง elif แล้ว
if money >= 100:
    print("Rich")
elif money >= 50:  # ถึงบรรทัดนี้ เงินต้อง < 100 แล้ว
    print("Normal")
else:              # ถึงบรรทัดนี้ เงินต้อง < 50 แล้ว
    print("Poor")
