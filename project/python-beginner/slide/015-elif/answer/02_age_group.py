# โจทย์: รับอายุ แล้วแสดงกลุ่มอายุ
# - น้อยกว่า 13  → Child
# - 13 ถึง 17   → Teen
# - 18 ขึ้นไป  → Adult

age = int(input())  # รับอายุเป็น int

# Python ตรวจเงื่อนไขจากบนลงล่าง
# เมื่อเจอเงื่อนไขที่เป็นจริง จะหยุดทันที
if age < 13:
    print("Child")
elif age <= 17:  # ถึงบรรทัดนี้ อายุต้อง >= 13 แล้ว
    print("Teen")
else:            # ถึงบรรทัดนี้ อายุต้อง >= 18 แล้ว
    print("Adult")
