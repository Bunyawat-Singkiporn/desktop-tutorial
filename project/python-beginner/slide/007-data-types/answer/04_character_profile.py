# โจทย์: สร้างโปรไฟล์ตัวละครโดยใช้ครบ 4 data types

# ข้อมูลตัวละคร (ใช้ครบทั้ง 4 types)
hero_name = "Shadow"        # str
hero_level = 10             # int
hero_hp = 99.5              # float
is_alive = True             # bool

# แสดงโปรไฟล์
print("=== Character Profile ===")
print("Name:", hero_name)
print("Level:", hero_level)
print("HP:", hero_hp)
print("Alive:", is_alive)
