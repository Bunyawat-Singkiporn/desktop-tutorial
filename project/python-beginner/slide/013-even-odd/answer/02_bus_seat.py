# โจทย์: รับหมายเลขที่นั่ง แล้วบอกว่าเป็นที่นั่งแบบไหน
# - เลขคู่ → Window Seat (ติดหน้าต่าง)
# - เลขคี่ → Aisle Seat (ติดทางเดิน)

seat = int(input())  # รับหมายเลขที่นั่งเป็น int

# ใช้ % 2 เพื่อตรวจว่าหารด้วย 2 เหลือเศษเท่าไหร่
# ถ้าเหลือเศษ 0 = เลขคู่
if seat % 2 == 0:
    print("Window Seat")
else:
    # ถ้าเหลือเศษ 1 = เลขคี่
    print("Aisle Seat")
