# โจทย์: รับ N แล้ววนเลข 1 ถึง N
# - หารด้วย 3 และ 5 ลงตัว → FizzBuzz
# - หารด้วย 3 ลงตัว (เท่านั้น) → Fizz
# - หารด้วย 5 ลงตัว (เท่านั้น) → Buzz
# - อื่น ๆ → แสดงตัวเลขนั้น
# ผสมความรู้: for loop + % (modulo) + elif

n = int(input())  # รับจำนวนรอบ

for i in range(1, n + 1):
    # ตรวจเงื่อนไขที่แคบที่สุดก่อน (หารทั้ง 3 และ 5)
    # ถ้าตรวจ % 3 ก่อน จะได้ "Fizz" แทนที่จะเป็น "FizzBuzz"
    if i % 3 == 0 and i % 5 == 0:
        print("FizzBuzz")
    elif i % 3 == 0:   # หารด้วย 3 ลงตัว (แต่ไม่ใช่ 5)
        print("Fizz")
    elif i % 5 == 0:   # หารด้วย 5 ลงตัว (แต่ไม่ใช่ 3)
        print("Buzz")
    else:
        print(i)       # ไม่ผ่านเงื่อนไขใดเลย แสดงเลขปกติ
